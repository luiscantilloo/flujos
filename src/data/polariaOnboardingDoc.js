import { POLARIA_WMS, POLARIA_STATUS_CALLOUT, POLARIA_ENV_VARS } from './polariaWmsMeta.js'

function envTable(rows) {
  const lines = ['| Variable | Obligatorio | Notas |', '| --- | --- | --- |']
  for (const row of rows) {
    const req = row.required ? 'Sí' : 'No'
    const notes = [row.note, row.default ? `default \`${row.default}\`` : ''].filter(Boolean).join(' · ') || '—'
    lines.push(`| \`${row.name}\` | ${req} | ${notes} |`)
  }
  return lines.join('\n')
}

