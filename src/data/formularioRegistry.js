export const FORMULARIO_SCHEMA_DIR = '/docs/formularios/schemas'

export function getFormularioItemById(id) {
  return formularioItems.find((item) => item.id === id) ?? null
}

export function getFormularioItemsByRole(roleId) {
  return formularioItems.filter((item) => item.roles.includes(roleId))
}

export function formularioSchemaPath(item) {
  return `${FORMULARIO_SCHEMA_DIR}/${item.schemaFile}`
}
